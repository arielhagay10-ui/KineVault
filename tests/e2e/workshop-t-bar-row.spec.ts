import { randomUUID } from "node:crypto";
import { createClient } from "@supabase/supabase-js";
import { expect, test } from "@playwright/test";
import { cleanupLocalFixture } from "../helpers/local-fixtures";
import { addWorkshopEquipment, dismissWorkshopTutorial, selectWorkshopObject, openWorkshopTool } from "./workshop-menu.helpers";

test.use({ viewport: { width: 1440, height: 1000 }, launchOptions: { args: ["--use-gl=angle", "--use-angle=swiftshader"] } });

test("T-bar picker, default row, playback and private save survive reload", async ({ page }) => {
  test.setTimeout(240_000);
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL!;
  if (!["127.0.0.1", "localhost"].includes(new URL(url).hostname)) throw Error("Local fixtures only");
  const admin = createClient(url, process.env.SUPABASE_SERVICE_ROLE_KEY!, { auth: { persistSession: false } });
  const email = `tbar-browser-${randomUUID()}@example.test`, password = `Tbar-${randomUUID()}!`;
  const account = await admin.auth.admin.createUser({ email, password, email_confirm: true });
  if (account.error) throw account.error;
  const owner = createClient(url, process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY!, { auth: { persistSession: false } });
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  try {
    const login = await owner.auth.signInWithPassword({ email, password });
    if (login.error) throw login.error;
    await page.goto("/sign-in");
    await page.getByLabel("Email", { exact: true }).fill(email);
    await page.getByLabel("Password", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await page.goto("/my-exercises/new");
    await expect(page.locator('[data-anatomy-state="ready"]')).toBeVisible({ timeout: 60_000 });
    await dismissWorkshopTutorial(page);
    await addWorkshopEquipment(page, "Chest-supported T-bar row");
    await expect(page.locator('[data-equipment-state="ready"]')).toBeVisible({ timeout: 60_000 });
    await page.getByText("More", { exact: true }).click();
    await page.getByText("Recovery and shortcuts", { exact: true }).click();
    await page.getByRole("button", { name: "Reset to example", exact: true }).click();
    await page.getByText("More", { exact: true }).click();
    await page.getByLabel("Exercise name", { exact: true }).fill("Chest-supported T-bar row");
    await page.getByRole("button", { name: "Save exercise", exact: true }).click();
    await expect(page).toHaveURL(/\/my-exercises\/[0-9a-f-]+\/workshop$/, { timeout: 60_000 });
    await expect(page.getByText(/Saved privately|Saved at.*Private/)).toBeVisible();
    const before = await page.getByText(/^Preview time /).innerText();
    await page.getByRole("button", { name: "Play", exact: true }).click();
    await expect.poll(() => page.getByText(/^Preview time /).innerText()).not.toBe(before);
    await page.getByRole("button", { name: "Pause", exact: true }).click();
    await page.reload();
    await expect(page.locator('[data-equipment-state="ready"]')).toBeVisible({ timeout: 60_000 });
    await expect(page.getByLabel("Exercise name", { exact: true })).toHaveValue("Chest-supported T-bar row");
    const id = page.url().split("/").at(-2)!;
    const draft = await owner.from("private_exercises").select("content_id").eq("id", id).single();
    if (draft.error) throw draft.error;
    const saved = await owner.from("exercise_scenes").select("studio_layout").eq("content_id", draft.data.content_id).single();
    if (saved.error) throw saved.error;
    expect(saved.data.studio_layout.objects).toHaveLength(1);
    expect(saved.data.studio_layout.objects[0]).toMatchObject({ slug: "t-bar-row-machine", machineUse: true });
    expect(saved.data.studio_layout.objects[0].frames).toHaveLength(17);
    await selectWorkshopObject(page, "Chest-supported T-bar row");
    await openWorkshopTool(page, "Contacts");
    await page.getByLabel("T-bar grip", { exact: true }).selectOption("wide");
    await page.getByRole("button", { name: "Release foot support", exact: true }).click();
    await page.getByRole("button", { name: "Hold with left hand", exact: true }).click();
    await expect(page.getByRole("button", { name: "Stop using machine", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Save exercise", exact: true }).click();
    await expect(page.getByText(/Saved privately|Saved at.*Private/)).toBeVisible();
    await page.reload();
    await selectWorkshopObject(page, "Chest-supported T-bar row");
    await openWorkshopTool(page, "Contacts");
    await expect(page.getByLabel("T-bar grip", { exact: true })).toHaveValue("wide");
    await expect(page.getByRole("button", { name: "Restore foot support", exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "Hold with left hand", exact: true })).toHaveAttribute("aria-pressed", "true");
    expect(errors).toEqual([]);
  } finally { await cleanupLocalFixture({ admin, userId: account.data.user.id, email, password }); }
});
