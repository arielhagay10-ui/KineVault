import { randomUUID } from "node:crypto";
import { mkdirSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { expect, test } from "@playwright/test";
import { blankWorkshopScene } from "../../src/lib/motion/workshop";
import { cleanupLocalFixture } from "../helpers/local-fixtures";
import { addWorkshopEquipment, openWorkshopTool, selectWorkshopJoint, selectWorkshopMoment } from "./workshop-menu.helpers";

test.use({ launchOptions: { args: ["--use-gl=angle", "--use-angle=swiftshader"] } });

test("pose controls stay focused, show concise angles, and save faster repetitions", async ({ page }) => {
  test.setTimeout(120_000);
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL!;
  if (!["localhost", "127.0.0.1"].includes(new URL(url).hostname)) throw Error("Local fixtures required");
  const auth = { persistSession: false };
  const admin = createClient(url, process.env.SUPABASE_SERVICE_ROLE_KEY!, { auth });
  const owner = createClient(url, process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY!, { auth });
  const email = `usability-${randomUUID()}@example.test`, password = "WorkshopUsability2026!";
  const account = await admin.auth.admin.createUser({ email, password, email_confirm: true });
  if (account.error) throw account.error;
  try {
    const login = await owner.auth.signInWithPassword({ email, password });
    if (login.error) throw login.error;
    const scene = structuredClone(blankWorkshopScene);
    scene.keyframes = scene.keyframes.map(frame => ({ ...frame, poses: { "left-elbow": { x: 23.348515, y: 0, z: 0 } } }));
    const draft = await owner.rpc("save_workshop_draft", { p_scene: scene, p_name: "Faster rep fixture" });
    if (draft.error) throw draft.error;
    await page.setViewportSize({ width: 1651, height: 871 });
    await page.goto("/sign-in");
    await page.getByLabel("Email", { exact: true }).fill(email);
    await page.getByLabel("Password", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await page.goto(`/my-exercises/${draft.data}/workshop`);
    await expect(page.locator('[data-anatomy-state="ready"]')).toBeVisible({ timeout: 60_000 });
    await selectWorkshopJoint(page, "Left elbow");
    const angle = page.getByRole("textbox", { name: "Bend Left elbow degrees", exact: true });
    await expect(angle).toHaveValue("23.35");
    await angle.focus();
    await angle.press("Tab");
    const canvas = (await page.locator("canvas").boundingBox())!;
    await page.mouse.click(canvas.x + canvas.width / 2, canvas.y + canvas.height * .45);
    await expect(page.locator("#workshop-panel-pose")).toBeVisible();
    await openWorkshopTool(page, "Timeline");
    const finish = page.getByRole("textbox", { name: "Time to finish seconds", exact: true });
    await expect(finish).toBeVisible();
    await finish.fill("0.5");
    await finish.press("Enter");
    await selectWorkshopMoment(page, "Finish");
    await expect(page.getByLabel("Preview time", { exact: true })).toHaveValue("500");
    await expect(page.getByLabel("Preview time", { exact: true })).toHaveAttribute("max", "1000");
    await page.getByRole("button", { name: "Save exercise", exact: true }).click();
    await expect(page.getByText(/Saved at.*Private/)).toBeVisible();
    const content = await owner.from("private_exercises").select("content_id").eq("id", draft.data).single();
    if (content.error) throw content.error;
    const stored = await owner.from("exercise_scenes").select("id,duration_ms").eq("content_id", content.data.content_id).single();
    if (stored.error) throw stored.error;
    expect(stored.data.duration_ms).toBe(1000);
    const poses = await owner.from("motion_keyframes").select("position_ms,motion_joint_poses(rotation_x)").eq("scene_id", stored.data.id).order("position_ms");
    if (poses.error) throw poses.error;
    expect(poses.data.map(frame => frame.position_ms)).toEqual([0, 500, 1000]);
    // Persistence stores quaternion components; loading rounds the display angle.
    for (const frame of poses.data) expect(frame.motion_joint_poses[0].rotation_x).toBeCloseTo(Math.sin(23.35 * Math.PI / 360), 5);
    await page.reload();
    await openWorkshopTool(page, "Timeline");
    await expect(finish).toHaveValue("0.5");
    await addWorkshopEquipment(page, "Dumbbell");
    await openWorkshopTool(page, "Contacts");
    await page.getByRole("button", { name: "Hold with left hand", exact: true }).click();
    await selectWorkshopJoint(page, "Left elbow");
    const equipment = page.locator("#workshop-panel-pose details").filter({ has: page.getByText("Held equipment", { exact: true }) });
    await expect(equipment).not.toHaveAttribute("open", "");
    await expect(angle).toBeInViewport();
    mkdirSync(".local-artifacts/workshop-usability", { recursive: true });
    await page.screenshot({ path: ".local-artifacts/workshop-usability/pose-desktop.png" });
    await equipment.locator("summary").click();
    await expect(page.getByRole("button", { name: "Release weight", exact: true })).toBeVisible();
    await equipment.locator("summary").click();
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: ".local-artifacts/workshop-usability/pose-mobile.png" });
    const denseScene = structuredClone(blankWorkshopScene);
    denseScene.keyframes = [0, 1, 1600, 3200].map(timeMs => ({ timeMs, poses: {} }));
    const dense = await owner.rpc("save_workshop_draft", { p_scene: denseScene, p_name: "Closely spaced poses" });
    if (dense.error) throw dense.error;
    await page.setViewportSize({ width: 1651, height: 871 });
    await page.goto(`/my-exercises/${dense.data}/workshop`);
    await openWorkshopTool(page, "Timeline");
    await finish.fill("0.125");
    await finish.press("Enter");
    await expect(page.getByRole("alert").filter({ hasText: "Choose a longer time" })).toBeVisible();
    await expect(page.getByLabel("Preview time", { exact: true })).toHaveAttribute("max", "3200");
  } finally {
    await page.close();
    await cleanupLocalFixture({ admin, userId: account.data.user.id, email, password, owner });
  }
});
