import { randomUUID } from "node:crypto";
import { mkdirSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { expect, test } from "@playwright/test";
import { blankWorkshopScene, identityTransform } from "../../src/lib/motion/workshop";
import { createStudioObject } from "../../src/lib/motion/studio";
import { defaultBand } from "../../src/lib/motion/studio-band";
import { cleanupLocalFixture } from "../helpers/local-fixtures";
import { dismissWorkshopTutorial, openWorkshopTool, selectWorkshopObject } from "./workshop-menu.helpers";

test.use({ launchOptions: { args: ["--use-gl=angle", "--use-angle=swiftshader"] } });

test("bands, props and free Smith grips survive edits, history and reload", async ({ page }) => {
  test.setTimeout(240_000);
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL!;
  if (!["localhost", "127.0.0.1"].includes(new URL(url).hostname)) throw new Error("Local fixtures required");
  const admin = createClient(url, process.env.SUPABASE_SERVICE_ROLE_KEY!, { auth: { persistSession: false } });
  const email = `versatile-${randomUUID()}@example.test`, password = "EquipmentFixture2026!";
  const account = await admin.auth.admin.createUser({ email, password, email_confirm: true });
  if (account.error) throw account.error;
  const owner = createClient(url, process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY!, { auth: { persistSession: false } });
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  try {
    await owner.auth.signInWithPassword({ email, password });
    const scene = structuredClone(blankWorkshopScene);
    const stool = { ...createStudioObject("stool", randomUUID(), 0), x: -.8 };
    const box = { ...createStudioObject("plyo-box", randomUUID(), 1), x: 1.2, rotationY: 20 };
    const smith = { ...createStudioObject("smith-machine", randomUUID(), 2), ...identityTransform, machineUse: false, machineRange: { min: .4, max: 2.8 }, machinePosition: .5 };
    const band = { ...createStudioObject("resistance-band", randomUUID(), 3), band: defaultBand() };
    band.band.start = { target: "equipment", objectId: stool.id, point: { x: 0, y: .6, z: 0 } };
    band.band.end = { target: "right-hand", point: { x: -.03, y: -.15, z: .13 } };
    scene.studio!.objects = [stool, box, smith, band];
    const created = await owner.rpc("create_workshop_exercise", { p_scene: scene });
    if (created.error) throw created.error;
    await page.goto("/sign-in");
    await page.getByLabel("Email", { exact: true }).fill(email);
    await page.getByLabel("Password", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await page.goto(`/my-exercises/${created.data}/workshop`);
    await expect(page.locator('[data-anatomy-state="ready"]')).toBeVisible({ timeout: 60_000 });
    await expect(page.locator('[data-equipment-state="ready"]')).toBeVisible({ timeout: 60_000 });
    await dismissWorkshopTutorial(page);
    await selectWorkshopObject(page, "Resistance band");
    await openWorkshopTool(page, "Contacts");
    await expect(page.getByLabel("Band start attachment", { exact: true })).toHaveValue("equipment");
    await page.getByLabel("Band end attachment", { exact: true }).selectOption("left-foot");
    await page.getByRole("button", { name: "Undo", exact: true }).click();
    await expect(page.getByLabel("Band end attachment", { exact: true })).toHaveValue("right-hand");
    await page.getByRole("button", { name: "Redo", exact: true }).click();
    await expect(page.getByLabel("Band end attachment", { exact: true })).toHaveValue("left-foot");
    await page.setViewportSize({ width: 390, height: 844 });
    const editControls = page.getByRole("button", { name: "Edit controls", exact: true });
    if (await editControls.isVisible()) await editControls.click();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.setViewportSize({ width: 1440, height: 1000 });
    await selectWorkshopObject(page, "Smith machine");
    await openWorkshopTool(page, "Contacts");
    await page.getByRole("button", { name: "Hold with left hand", exact: true }).click();
    await expect(page.getByRole("button", { name: "Use this machine", exact: true })).toBeVisible();
    await page.getByLabel("Lowest bar height meters", { exact: true }).fill("0.3");
    await page.getByLabel("Lowest bar height meters", { exact: true }).press("Enter");
    await page.getByRole("button", { name: "Save exercise", exact: true }).click();
    await expect(page.getByText(/Saved at.*Private/)).toBeVisible();
    await page.reload();
    await expect(page.locator('[data-equipment-state="ready"]')).toBeVisible({ timeout: 60_000 });
    await selectWorkshopObject(page, "Smith machine"); await openWorkshopTool(page, "Contacts");
    await expect(page.getByLabel("Lowest bar height meters", { exact: true })).toHaveValue("0.3");
    await expect(page.getByRole("button", { name: "Hold with left hand", exact: true })).toHaveAttribute("aria-pressed", "true");
    await selectWorkshopObject(page, "Resistance band"); await openWorkshopTool(page, "Contacts");
    await expect(page.getByLabel("Band end attachment", { exact: true })).toHaveValue("left-foot");
    mkdirSync(".local-artifacts/equipment-expansion", { recursive: true });
    await page.screenshot({ path: ".local-artifacts/equipment-expansion/band-props.png", fullPage: true });
    await selectWorkshopObject(page, "Stool"); await openWorkshopTool(page, "Item settings");
    await page.getByRole("button", { name: "Remove item", exact: true }).click();
    await selectWorkshopObject(page, "Resistance band"); await openWorkshopTool(page, "Contacts");
    await expect(page.getByLabel("Band start attachment", { exact: true })).toHaveValue("fixed");
    await page.getByRole("button", { name: "Save exercise", exact: true }).click();
    await expect(page.getByText(/Saved at.*Private/)).toBeVisible();
    expect(errors).toEqual([]);
  } finally {
    await cleanupLocalFixture({ admin, userId: account.data.user.id, email, password });
  }
});
